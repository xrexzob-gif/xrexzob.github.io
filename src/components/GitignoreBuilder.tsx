import React, { useState, useMemo } from 'react';
import { GITIGNORE_OPTIONS, GitignoreOption } from '../data/gitignoreTemplates';
import { useLanguage } from '../context/LanguageContext';
import {
  FileText,
  Copy,
  Check,
  Download,
  Shield,
  Layers,
  Code
} from 'lucide-react';

export const GitignoreBuilder: React.FC = () => {
  const { t } = useLanguage();
  const [selectedIds, setSelectedIds] = useState<string[]>([
    'env', 'node', 'build-web', 'vscode', 'macos'
  ]);
  const [copied, setCopied] = useState(false);

  const toggleOption = (id: string) => {
    if (selectedIds.includes(id)) {
      setSelectedIds(selectedIds.filter((item) => item !== id));
    } else {
      setSelectedIds([...selectedIds, id]);
    }
  };

  const selectAll = () => {
    setSelectedIds(GITIGNORE_OPTIONS.map((o) => o.id));
  };

  const clearAll = () => {
    setSelectedIds(['env']);
  };

  const combinedContent = useMemo(() => {
    let output = `# ===========================================\n`;
    output += `# Generated by GitForge (.gitignore Generator)\n`;
    output += `# Tanggal dibuat: ${new Date().toISOString().split('T')[0]}\n`;
    output += `# ===========================================\n\n`;

    selectedIds.forEach((id) => {
      const opt = GITIGNORE_OPTIONS.find((o) => o.id === id);
      if (opt) {
        output += opt.content + '\n';
      }
    });

    return output;
  }, [selectedIds]);

  const handleCopy = () => {
    navigator.clipboard.writeText(combinedContent);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  const handleDownload = () => {
    const blob = new Blob([combinedContent], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = '.gitignore';
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="border-b border-slate-800 pb-4">
        <h2 className="text-xl sm:text-2xl font-bold text-white tracking-tight">
          {t('gitignoreTitle')}
        </h2>
        <p className="text-xs sm:text-sm text-slate-400 mt-1">
          {t('gitignoreSubtitle')}
        </p>
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6 items-start">
        {/* Left Selection Grid (5 cols) */}
        <div className="lg:col-span-5 space-y-4 bg-slate-900/60 border border-slate-800 rounded-xl p-5">
          <div className="flex items-center justify-between pb-2 border-b border-slate-800">
            <span className="text-xs font-semibold text-slate-300">
              {t('selectStacks')} ({selectedIds.length} aktif)
            </span>
            <div className="flex items-center gap-2 text-xs">
              <button
                onClick={selectAll}
                className="text-cyan-400 hover:underline cursor-pointer"
              >
                Pilih Semua
              </button>
              <span className="text-slate-600">·</span>
              <button
                onClick={clearAll}
                className="text-slate-400 hover:text-slate-200 cursor-pointer"
              >
                Reset
              </button>
            </div>
          </div>

          <div className="grid grid-cols-1 gap-2 max-h-[520px] overflow-y-auto pr-1">
            {GITIGNORE_OPTIONS.map((option) => {
              const isSelected = selectedIds.includes(option.id);
              const isSecurity = option.category === 'security';

              return (
                <button
                  key={option.id}
                  onClick={() => toggleOption(option.id)}
                  className={`w-full flex items-center justify-between p-3 rounded-lg border text-left transition-all cursor-pointer ${
                    isSelected
                      ? isSecurity
                        ? 'bg-amber-950/20 border-amber-600/50 text-amber-200 font-medium'
                        : 'bg-cyan-500/10 border-cyan-500/50 text-white font-medium'
                      : 'bg-slate-950 border-slate-800/80 text-slate-400 hover:border-slate-700'
                  }`}
                >
                  <div className="flex items-center gap-2.5">
                    <input
                      type="checkbox"
                      checked={isSelected}
                      readOnly
                      className="rounded border-slate-700 text-cyan-500 focus:ring-0 pointer-events-none"
                    />
                    <span className="text-xs sm:text-sm">{option.name}</span>
                  </div>
                  <span className="text-[10px] font-mono uppercase text-slate-500">
                    {option.category}
                  </span>
                </button>
              );
            })}
          </div>
        </div>

        {/* Right Output Area (7 cols) */}
        <div className="lg:col-span-7 bg-slate-900/60 border border-slate-800 rounded-xl overflow-hidden flex flex-col">
          <div className="flex items-center justify-between px-4 py-3 border-b border-slate-800 bg-slate-950/80">
            <span className="font-mono text-xs text-slate-400">.gitignore</span>
            <div className="flex items-center gap-2">
              <button
                onClick={handleCopy}
                className="flex items-center gap-1.5 px-3 py-1.5 bg-slate-800 hover:bg-slate-700 text-slate-200 rounded-lg text-xs font-medium transition-colors cursor-pointer"
              >
                {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
                <span>{copied ? t('copiedToast') : t('copyGitignore')}</span>
              </button>
              <button
                onClick={handleDownload}
                className="flex items-center gap-1.5 px-3 py-1.5 bg-cyan-500 hover:bg-cyan-400 text-slate-950 rounded-lg text-xs font-semibold transition-colors cursor-pointer"
              >
                <Download className="w-3.5 h-3.5" />
                <span>{t('downloadGitignore')}</span>
              </button>
            </div>
          </div>

          <div className="p-4 bg-slate-950/90 overflow-x-auto min-h-[500px]">
            <pre className="font-mono text-xs text-slate-300 leading-relaxed whitespace-pre select-all">
              {combinedContent}
            </pre>
          </div>
        </div>
      </div>
    </div>
  );
};
